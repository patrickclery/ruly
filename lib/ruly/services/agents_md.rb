# frozen_string_literal: true

module Ruly
  module Services
    # AGENTS.md output target (`ruly squash RECIPE -a agents`).
    # Writes the recipe's squashed rules to AGENTS.md under a generated-file header,
    # so any AGENTS.md-aware agent can read a ruly recipe. Claude-only recipe parts
    # (commands, subagents, hooks, MCP servers, settings) are never emitted.
    module AgentsMd
      module_function

      AGENT = 'agents'
      OUTPUT_FILE = 'AGENTS.md'
      MARKER = '<!-- Generated by ruly'
      CLAUDE_DEFAULT_OUTPUT = 'CLAUDE.local.md'
      NOTICE_PREFIX = "\u2139\uFE0F  AGENTS.md target skips Claude-only parts: "
      FRONTMATTER = /\A---\s*\n.*?^---\s*$\n?/m
      FENCE = /\A\s*(```|~~~)/
      HEADING = /\A(\#{1,6})(\s.*)?\z/

      # Resolve the output path for an agent.
      # @param requested [String, nil] the -o value (Thor default 'CLAUDE.local.md')
      # @param agent [String] normalized agent name
      # @return [String, nil] AGENTS.md for the agents target unless -o was explicit; else requested
      def output_file(requested, agent)
        return requested unless agent == AGENT
        return OUTPUT_FILE if requested.nil? || requested == CLAUDE_DEFAULT_OUTPUT

        requested
      end

      # Whether a file was written by ruly (line 1 starts with the ruly marker).
      # Reads only the first line.
      # @param path [String] file path
      # @return [Boolean]
      def generated?(path)
        return false unless File.file?(path)

        File.open(path, &:gets).to_s.start_with?(MARKER)
      rescue SystemCallError
        false
      end

      # Generated-file header written on line 1.
      # @param recipe_name [String, nil] recipe name
      # @return [String] HTML comment header
      def header(recipe_name)
        return "#{MARKER} — do not edit -->" unless recipe_name

        "#{MARKER} from recipe: #{recipe_name} — do not edit -->"
      end

      # Write AGENTS.md: header, optional TOC, the squashed rules body, then skills under ## Skills.
      # @param output_file [String] destination path
      # @param local_sources [Array<Hash>] processed rule sources
      # @param recipe_name [String, nil] recipe name for the header
      # @param script_mappings [Hash] absolute script path => relative name
      # @param skill_files [Array<Hash>] processed skill sources, inlined as plain sections
      # @param toc [Boolean] whether to write a table of contents
      def write(output_file, local_sources:, recipe_name:, script_mappings:, skill_files:, toc:)
        rendered = skill_files.map { |skill| skill.merge(content: render_skill(skill)) }
        File.open(output_file, 'w') do |io|
          io.puts header(recipe_name)
          io.puts
          if toc
            io.puts Services::TOCGenerator.generate_toc_content(local_sources + rendered, [], AGENT)
            io.puts
          end
          Services::SquashHelpers.write_sources(io, local_sources, script_mappings, toc:)
          write_skills(io, rendered, script_mappings, toc:)
        end
      end

      # @param io [IO] destination
      # @param rendered [Array<Hash>] skills with rendered :content
      def write_skills(io, rendered, script_mappings, toc:)
        return if rendered.empty?

        io.puts
        io.puts '## Skills'
        io.puts
        Services::SquashHelpers.write_sources(io, rendered, script_mappings, toc:)
      end

      # Render a skill as a plain AGENTS.md section: leading frontmatter dropped, headings
      # demoted two levels (capped at h6, fenced code untouched), a name heading prepended
      # when the body does not start with a heading.
      # @param skill [Hash] processed skill with :content and :path
      # @return [String] rendered markdown
      def render_skill(skill)
        body = skill[:content].to_s.sub(FRONTMATTER, '')
        body = demote_headings(body)
        first = body.each_line.find { |line| !line.strip.empty? }
        return body if first&.chomp&.match?(HEADING)

        "### #{Services::ScriptManager.derive_skill_name(skill[:path])}\n\n#{body}"
      end

      # Demote ATX headings by two levels outside fenced code blocks.
      # @param text [String] markdown
      # @return [String] markdown with demoted headings
      def demote_headings(text)
        in_fence = false
        text.each_line.map do |line|
          if line.match?(FENCE)
            in_fence = !in_fence
            next line
          end
          next line if in_fence || !(match = line.chomp.match(HEADING))

          "#{'#' * [match[1].length + 2, 6].min}#{match[2]}#{line[/\R\z/]}"
        end.join
      end

      # Claude-only recipe parts the agents target does not emit (names and counts only).
      # @param recipe_config [Hash, Array] recipe configuration
      # @param command_files [Array<Hash>] processed command files
      # @param local_sources [Array<Hash>] processed rule sources (frontmatter mcp_servers)
      # @return [Array<String>] parts in order commands, subagents, hooks, mcp_servers, model, isolate
      def skipped_parts(recipe_config, command_files:, local_sources:)
        parts = []
        parts << "commands (#{command_files.size})" unless command_files.empty?
        return parts unless recipe_config.is_a?(Hash)

        subagents = recipe_config['subagents']
        parts << "subagents (#{subagents.size})" if subagents.is_a?(Array) && !subagents.empty?
        parts << 'hooks' if recipe_config['hooks'].is_a?(Hash) && !recipe_config['hooks'].empty?
        parts << 'mcp_servers' if mcp_servers?(recipe_config, local_sources)
        parts << 'model' if recipe_config['model'].is_a?(String) && !recipe_config['model'].empty?
        parts << 'isolate' if recipe_config['isolate'] == true
        parts
      end

      def mcp_servers?(recipe_config, local_sources)
        Array(recipe_config['mcp_servers']).any? ||
          Services::MCPManager.collect_mcp_servers_from_sources(local_sources).any?
      end

      # @param parts [Array<String>] skipped part names
      # @return [String, nil] one-line notice, nil when nothing is skipped
      def skipped_notice(parts)
        return if parts.empty?

        "#{NOTICE_PREFIX}#{parts.join(', ')}"
      end
    end
  end
end
