# frozen_string_literal: true

module Ruly
  module Services
    # AGENTS.md output target (`ruly squash RECIPE -a agents`).
    # Writes the recipe's squashed rules to AGENTS.md under a generated-file header,
    # so any AGENTS.md-aware agent can read a ruly recipe. Claude-only recipe parts
    # (commands, subagents, hooks, MCP servers, settings) are never emitted.
    module AgentsMd
      module_function

      AGENT = 'agents'
      OUTPUT_FILE = 'AGENTS.md'
      MARKER = '<!-- Generated by ruly'
      CLAUDE_DEFAULT_OUTPUT = 'CLAUDE.local.md'

      # Resolve the output path for an agent.
      # @param requested [String, nil] the -o value (Thor default 'CLAUDE.local.md')
      # @param agent [String] normalized agent name
      # @return [String, nil] AGENTS.md for the agents target unless -o was explicit; else requested
      def output_file(requested, agent)
        return requested unless agent == AGENT
        return OUTPUT_FILE if requested.nil? || requested == CLAUDE_DEFAULT_OUTPUT

        requested
      end

      # Generated-file header written on line 1.
      # @param recipe_name [String, nil] recipe name
      # @return [String] HTML comment header
      def header(recipe_name)
        return "#{MARKER} — do not edit -->" unless recipe_name

        "#{MARKER} from recipe: #{recipe_name} — do not edit -->"
      end

      # Write AGENTS.md: header, optional TOC, the squashed rules body.
      # @param output_file [String] destination path
      # @param local_sources [Array<Hash>] processed rule sources
      # @param recipe_name [String, nil] recipe name for the header
      # @param script_mappings [Hash] absolute script path => relative name
      # @param toc [Boolean] whether to write a table of contents
      def write(output_file, local_sources:, recipe_name:, script_mappings:, toc:)
        File.open(output_file, 'w') do |io|
          io.puts header(recipe_name)
          io.puts
          if toc
            io.puts Services::TOCGenerator.generate_toc_content(local_sources, [], AGENT)
            io.puts
          end
          Services::SquashHelpers.write_sources(io, local_sources, script_mappings, toc:)
        end
      end
    end
  end
end
