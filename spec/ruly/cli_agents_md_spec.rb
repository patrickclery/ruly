# frozen_string_literal: true

require 'spec_helper'
require 'tmpdir'
require 'fileutils'

RSpec.describe Ruly::CLI, '.start -a agents' do
  let(:test_dir) { Dir.mktmpdir }
  let(:fixture_dir) { File.expand_path('../fixtures/agents_md', __dir__) }
  let(:demo_header) { '<!-- Generated by ruly from recipe: demo — do not edit -->' }
  let(:claude_body) { "\n# Demo Rule\n\nSee [Base Rule](#base-rule).\n\n# Base Rule\n\nShared base.\n" }

  around do |example|
    original_dir = Dir.pwd
    begin
      Dir.chdir(test_dir)
      example.run
    ensure
      # CRITICAL: Always return to original directory before ANY cleanup
      Dir.chdir(original_dir)
      FileUtils.rm_rf(test_dir) if test_dir && Dir.exist?(test_dir)
    end
  end

  before do
    FileUtils.cp_r(File.join(fixture_dir, '.'), test_dir)
    allow(Ruly::Services::RecipeLoader).to receive(:user_recipes_file)
      .and_return(File.join(test_dir, 'no-user-recipes.yml'))
  end

  def read_utf8(path) = File.read(path, encoding: 'UTF-8')

  def capture_stdout
    original = $stdout
    $stdout = StringIO.new
    yield
    $stdout.string
  ensure
    $stdout = original
  end

  def run_cli(*args)
    expect { described_class.start(args) }.to output.to_stdout
  end

  context 'when squashing with -a agents' do
    before { run_cli('squash', 'demo', '-a', 'agents') }

    let(:content) { read_utf8('AGENTS.md') }

    it 'writes the demo header on line 1' do
      expect(content.lines.first.chomp).to eq(demo_header)
    end

    it 'includes the rule and its requires: target in order' do
      expect(content.index('# Demo Rule')).to be < content.index('# Base Rule')
    end

    it 'writes the same body the claude target gets after the header' do
      expect(content.lines.drop(2).join).to start_with(claude_body)
    end

    it 'writes no Claude-only artifacts' do
      %w[CLAUDE.local.md .claude/agents .claude/settings.local.json .mcp.json .mcp.yml].each do |path|
        expect(File.exist?(path)).to be(false), "expected #{path} to be absent"
      end
    end
  end

  context 'with the agents-md and agentsmd aliases' do
    %w[agents-md agentsmd].each do |alias_name|
      it "writes AGENTS.md for -a #{alias_name}" do
        run_cli('squash', 'demo', '-a', alias_name)
        expect(read_utf8('AGENTS.md').lines.first.chomp).to eq(demo_header)
      end
    end
  end

  context 'with -o docs/AGENTS.md' do
    it 'writes the explicit path and no ./AGENTS.md' do
      run_cli('squash', 'demo', '-a', 'agents', '-o', 'docs/AGENTS.md')
      expect(read_utf8('docs/AGENTS.md').lines.first.chomp).to eq(demo_header)
      expect(File.exist?('AGENTS.md')).to be(false)
    end
  end

  context 'when squashing a recipe with skills and Claude-only parts' do
    let!(:stdout) { capture_stdout { described_class.start(%w[squash demo -a agents]) } }
    let(:lines) { read_utf8('AGENTS.md').lines.map(&:chomp) }
    let(:notice) { 'AGENTS.md target skips Claude-only parts: commands (1), subagents (1), hooks, mcp_servers' }

    it 'inlines skills under ## Skills after the rules' do
      expect(lines.index('## Skills')).to be > lines.index('# Base Rule')
      expect(lines.index('### Deploy Skill')).to be > lines.index('## Skills')
      expect(lines).to include('#### Rollback', '# deploy comment')
      expect(lines).not_to include('### deploy')
    end

    it 'emits no command body and no skill or command directories' do
      expect(lines).not_to include('# Ship')
      expect(Dir.exist?('.claude/skills')).to be(false)
      expect(Dir.exist?('.claude/commands')).to be(false)
    end

    it 'prints the skipped-parts notice once with names only' do
      expect(stdout.scan(notice).size).to eq(1)
      notice_line = stdout.lines.find { |l| l.include?('skips Claude-only parts') }
      expect(notice_line).not_to include('echo done')
      expect(notice_line).not_to include('grafana')
    end
  end

  context 'with --dry-run' do
    let!(:stdout) { capture_stdout { described_class.start(%w[squash demo -a agents --dry-run]) } }

    it 'reports the AGENTS.md plan and notice without writing' do
      expect(stdout).to include('Would create: AGENTS.md', '1 skill files inlined under ## Skills',
                                'skips Claude-only parts')
      expect(File.exist?('AGENTS.md')).to be(false)
    end
  end

  context 'with a skill heading that collides with a rule anchor' do
    before do
      skill = 'rules/skills/deploy.md'
      File.write(skill, File.read(skill).sub('# Deploy Skill', '# Base Rule'))
      allow(Ruly::Services::MCPManager).to receive(:update_mcp_settings)
    end

    it 'reports the ambiguous link for -a agents' do
      out = capture_stdout { described_class.start(%w[squash demo -a agents]) }
      expect(out).to include('Ambiguous markdown link references detected')
    end

    it 'does not report it for -a claude' do
      out = capture_stdout { described_class.start(%w[squash demo -a claude]) }
      expect(out).not_to include('Ambiguous markdown link references detected')
    end
  end

  context 'with --toc' do
    it 'keeps the header on line 1 and lists skills in the TOC' do
      run_cli('squash', 'demo', '-a', 'agents', '-t')
      content = read_utf8('AGENTS.md')
      expect(content.lines.first.chomp).to eq(demo_header)
      expect(content).to include('## Table of Contents')
      toc = content.split('## Table of Contents').last.split('<a id=').first
      expect(toc).to include('Deploy Skill')
    end
  end

  context 'when cleaning with -a agents' do
    before do
      File.write('AGENTS.md', "#{demo_header}\n\nbody\n")
      FileUtils.mkdir_p('.claude')
      File.write('.claude/keep.txt', "keep\n")
      File.write('.mcp.json', "{}\n")
      File.write('CLAUDE.local.md', "# mine\n")
    end

    it 'removes only the generated AGENTS.md' do
      run_cli('clean', '-a', 'agents')
      expect(File.exist?('AGENTS.md')).to be(false)
      expect(%w[.claude/keep.txt .mcp.json CLAUDE.local.md].map { |f| File.exist?(f) }).to all(be(true))
    end

    it 'lists AGENTS.md under Would remove: in a dry run and deletes nothing' do
      out = capture_stdout { described_class.start(%w[clean -a agents --dry-run]) }
      expect(out).to match(/Would remove:\n\s+- AGENTS\.md\n?\z/)
      expect(File.exist?('AGENTS.md')).to be(true)
    end

    it 'removes the generated file at an explicit -o path only' do
      FileUtils.mkdir_p('docs')
      File.write('docs/AGENTS.md', "#{demo_header}\n")
      run_cli('clean', '-a', 'agents', '-o', 'docs/AGENTS.md')
      expect(File.exist?('docs/AGENTS.md')).to be(false)
      expect(File.exist?('AGENTS.md')).to be(true)
    end
  end

  context 'with a hand-written AGENTS.md' do
    before { File.write('AGENTS.md', "# Team notes\n") }

    it 'keeps it on clean and says why' do
      expect do
        expect { described_class.start(%w[clean -a agents]) }.to output(/Already clean/).to_stdout
      end.to output(/not generated by ruly/).to_stderr
      expect(read_utf8('AGENTS.md')).to eq("# Team notes\n")
    end

    [%w[squash demo -a agents], %w[squash demo -a agents --dry-run]].each do |args|
      it "refuses #{args.join(' ')} with exit 1" do
        expect do
          expect { described_class.start(args) }.to raise_error(SystemExit) { |e| expect(e.status).to eq(1) }
        end.to output(/not generated by ruly/).to_stderr
        expect(read_utf8('AGENTS.md')).to eq("# Team notes\n")
      end
    end
  end

  context 'with --clean over a generated AGENTS.md' do
    it 'rewrites it and keeps .claude/keep.txt' do
      File.write('AGENTS.md', "#{demo_header}\n\nstale\n")
      FileUtils.mkdir_p('.claude')
      File.write('.claude/keep.txt', "keep\n")
      run_cli('squash', 'demo', '-a', 'agents', '--clean')
      expect(read_utf8('AGENTS.md')).to include('# Demo Rule')
      expect(read_utf8('AGENTS.md')).not_to include('stale')
      expect(File.exist?('.claude/keep.txt')).to be(true)
    end
  end

  context 'with --git-ignore and --git-exclude' do
    it 'adds AGENTS.md to .gitignore and no commands directory' do
      run_cli('squash', 'demo', '-a', 'agents', '-i')
      lines = File.read('.gitignore').lines.map(&:chomp)
      expect(lines).to include('AGENTS.md')
      expect(lines).not_to include('.claude/commands/')
    end

    it 'adds AGENTS.md to .git/info/exclude' do
      FileUtils.mkdir_p('.git/info')
      run_cli('squash', 'demo', '-a', 'agents', '-I')
      expect(File.read('.git/info/exclude').lines.map(&:chomp)).to include('AGENTS.md')
    end
  end

  context 'when both targets run with -i or -I' do
    before do
      FileUtils.mkdir_p('.git/info')
      allow(Ruly::Services::MCPManager).to receive(:update_mcp_settings)
    end

    def ruly_section(path)
      lines = File.read(path).lines.map(&:chomp)
      start = lines.index('# Ruly generated files')
      lines[(start + 1)..].take_while { |line| !line.empty? && !line.start_with?('#') }
    end

    {'-I' => '.git/info/exclude', '-i' => '.gitignore'}.each do |flag, path|
      it "keeps the claude entries when -a agents #{flag} runs second" do
        run_cli('squash', 'demo', flag)
        run_cli('squash', 'demo', '-a', 'agents', flag)
        expect(ruly_section(path)).to eq(['CLAUDE.local.md', '.claude/commands/', 'AGENTS.md'])
      end

      it "keeps AGENTS.md when the claude target #{flag} runs second" do
        run_cli('squash', 'demo', '-a', 'agents', flag)
        run_cli('squash', 'demo', flag)
        expect(ruly_section(path)).to eq(['AGENTS.md', 'CLAUDE.local.md', '.claude/commands/'])
      end

      it "does not duplicate entries when the same target #{flag} runs twice" do
        2.times { run_cli('squash', 'demo', '-a', 'agents', flag) }
        expect(ruly_section(path)).to eq(['AGENTS.md'])
      end
    end
  end
end
