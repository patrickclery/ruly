# frozen_string_literal: true

require 'spec_helper'
require 'tmpdir'
require 'fileutils'

RSpec.describe Ruly::Services::ClaudePlugin do
  let(:test_dir) { Dir.mktmpdir }

  around do |example|
    original_dir = Dir.pwd
    begin
      Dir.chdir(test_dir)
      example.run
    ensure
      # CRITICAL: Always return to original directory before ANY cleanup
      Dir.chdir(original_dir)
      FileUtils.rm_rf(test_dir) if test_dir && Dir.exist?(test_dir)
    end
  end

  def write_manifest(dir, data)
    FileUtils.mkdir_p(File.join(dir, '.claude-plugin'))
    File.write(File.join(dir, '.claude-plugin', 'plugin.json'), data.is_a?(String) ? data : JSON.generate(data))
  end

  describe '.output_dir' do
    it 'defaults to ruly-plugin-NAME without -o' do
      expect(described_class.output_dir(nil, 'demo')).to eq('ruly-plugin-demo')
    end

    it 'treats the Thor default CLAUDE.local.md as no -o' do
      expect(described_class.output_dir('CLAUDE.local.md', 'demo')).to eq('ruly-plugin-demo')
    end

    it 'drops a trailing slash from -o' do
      expect(described_class.output_dir('out/', 'demo')).to eq('out')
    end

    it 'uses a custom -o verbatim' do
      expect(described_class.output_dir('custom', 'demo')).to eq('custom')
    end
  end

  describe '.manifest' do
    let(:config) { {'description' => 'A recipe'} }

    it 'writes name, version, description, author and metadata in order' do
      manifest = described_class.manifest('demo', config, author: 'Jane')
      expect(manifest.keys).to eq(%w[name version description author metadata])
    end

    it 'uses the gem version' do
      expect(described_class.manifest('demo', config, author: nil)['version']).to eq(Ruly::VERSION)
    end

    it 'marks the plugin as generated by ruly' do
      expect(described_class.manifest('demo', config, author: nil)['metadata'])
        .to eq('generator' => 'ruly', 'recipe' => 'demo')
    end

    it 'sets the author name when known' do
      expect(described_class.manifest('demo', config, author: 'Jane')['author']).to eq('name' => 'Jane')
    end

    it 'omits description and author when absent' do
      expect(described_class.manifest('demo', {}, author: nil).keys).to eq(%w[name version metadata])
    end
  end

  describe '.generated?' do
    it 'is true for a ruly manifest' do
      write_manifest('plug', {'metadata' => {'generator' => 'ruly'}, 'name' => 'demo'})
      expect(described_class.generated?('plug')).to be(true)
    end

    it 'is false for a missing dir' do
      expect(described_class.generated?('missing')).to be(false)
    end

    it 'is false for invalid JSON' do
      write_manifest('plug', '{not json')
      expect(described_class.generated?('plug')).to be(false)
    end

    it 'is false for a JSON Array' do
      write_manifest('plug', '[]')
      expect(described_class.generated?('plug')).to be(false)
    end

    it 'is false when another tool generated it' do
      write_manifest('plug', {'metadata' => {'generator' => 'other'}, 'name' => 'demo'})
      expect(described_class.generated?('plug')).to be(false)
    end
  end

  describe '.validate_recipe!' do
    it 'raises without a recipe' do
      expect { described_class.validate_recipe!(nil, {}) }.to raise_error(Ruly::Error, /needs a recipe/)
    end

    it 'raises for an Array recipe' do
      expect { described_class.validate_recipe!('demo', []) }.to raise_error(Ruly::Error, /needs a Hash recipe/)
    end

    ['../x', 'a/b', 'a b', 'a..b', '-x'].each do |name|
      it "raises for the unsafe name #{name.inspect}" do
        expect { described_class.validate_recipe!(name, {}) }
          .to raise_error(Ruly::Error, /not a valid plugin name/)
      end
    end

    it 'passes for a plain name' do
      expect { described_class.validate_recipe!('demo', {}) }.not_to raise_error
    end

    %w[claude Claude-Code claude-tools anthropic-x cc-plugin-y].each do |name|
      it "raises for the reserved name #{name}" do
        expect { described_class.validate_recipe!(name, {}) }
          .to raise_error(Ruly::Error, /reserved by Claude Code/)
      end
    end

    %w[core work_axle demo.v2].each do |name|
      it "passes for #{name}" do
        expect { described_class.validate_recipe!(name, {}) }.not_to raise_error
      end
    end
  end

  describe '.guard_dir!' do
    it 'refuses a non-empty dir ruly did not generate' do
      FileUtils.mkdir_p('plug')
      File.write('plug/notes.txt', "mine\n")
      expect { described_class.guard_dir!('plug') }.to raise_error(Ruly::Error, /not generated by ruly/)
    end

    it 'passes for a ruly-generated dir' do
      write_manifest('plug', {'metadata' => {'generator' => 'ruly'}})
      expect { described_class.guard_dir!('plug') }.not_to raise_error
    end

    it 'passes for a missing path and an empty dir' do
      FileUtils.mkdir_p('empty')
      expect { %w[missing empty].each { |dir| described_class.guard_dir!(dir) } }.not_to raise_error
    end

    it 'refuses an existing file' do
      File.write('somefile.txt', "x\n")
      expect { described_class.guard_dir!('somefile.txt') }.to raise_error(Ruly::Error, /is not a directory/)
    end

    ['.', '..', '/'].each do |dir|
      it "refuses #{dir} even with a ruly manifest" do
        allow(described_class).to receive(:generated?).and_return(true)
        expect { described_class.guard_dir!(dir) }.to raise_error(Ruly::Error, /Refusing to use/)
      end
    end

    it 'refuses the absolute working directory' do
      expect { described_class.guard_dir!(Dir.pwd) }.to raise_error(Ruly::Error, /Refusing to use/)
    end

    it 'refuses the home directory' do
      expect { described_class.guard_dir!(File.expand_path('~')) }.to raise_error(Ruly::Error, /Refusing to use/)
    end

    context 'with symlinks, // and ~' do
      let(:home) { File.join(test_dir, 'home') }

      before do
        FileUtils.mkdir_p(['work/sub', home])
        File.symlink(File.join(test_dir, 'work'), 'lnk')
        File.symlink(home, 'home-link')
        allow(Dir).to receive(:home).and_return(home)
        allow(described_class).to receive(:generated?).and_return(true)
      end

      it 'refuses a symlinked path to the working directory' do
        Dir.chdir('work') do
          expect { described_class.guard_dir!(File.join(test_dir, 'lnk')) }.to raise_error(Ruly::Error, /working dir/)
        end
      end

      it 'refuses a symlinked path to a parent of the working directory' do
        Dir.chdir('work/sub') do
          expect { described_class.guard_dir!('../../lnk') }.to raise_error(Ruly::Error, /Refusing to use/)
        end
      end

      it 'refuses a symlinked path to the home directory' do
        expect { described_class.guard_dir!('home-link') }.to raise_error(Ruly::Error, /Refusing to use/)
      end

      ['//', '//.'].each do |dir|
        it "refuses #{dir}" do
          expect { described_class.guard_dir!(dir) }.to raise_error(Ruly::Error, /Refusing to use/)
        end
      end

      it 'refuses //HOME' do
        expect { described_class.guard_dir!("/#{home}") }.to raise_error(Ruly::Error, /Refusing to use/)
      end

      ['~', '~nouser', '~/plug'].each do |dir|
        it "refuses #{dir} without expanding it" do
          expect { described_class.guard_dir!(dir) }.to raise_error(Ruly::Error, /leading '~' is not expanded/)
        end
      end

      it 'refuses to clean a symlinked path to the working directory' do
        Dir.chdir('work') do
          expect { expect(described_class.files_to_clean(File.join(test_dir, 'lnk'), 'demo')).to eq([]) }
            .to output(/Refusing to clean/).to_stderr
        end
      end
    end
  end

  describe '.files_to_clean' do
    it 'returns the default dir when ruly generated it' do
      write_manifest('ruly-plugin-demo', {'metadata' => {'generator' => 'ruly'}})
      expect(described_class.files_to_clean('CLAUDE.local.md', 'demo')).to eq(['ruly-plugin-demo/'])
    end

    it 'skips an unowned dir with a reason' do
      FileUtils.mkdir_p('ruly-plugin-demo')
      File.write('ruly-plugin-demo/notes.txt', "mine\n")
      expect { expect(described_class.files_to_clean(nil, 'demo')).to eq([]) }
        .to output(/not generated by ruly/).to_stderr
    end

    it 'returns nothing silently for a missing dir' do
      expect { expect(described_class.files_to_clean(nil, 'demo')).to eq([]) }.not_to output.to_stderr
    end

    [[nil, nil], ['CLAUDE.local.md', nil]].each do |requested, recipe|
      it "asks for RECIPE or -o DIR with #{requested.inspect} and no recipe" do
        expect { expect(described_class.files_to_clean(requested, recipe)).to eq([]) }
          .to output(/pass RECIPE or -o DIR/).to_stderr
      end
    end

    it 'refuses -o .' do
      expect { expect(described_class.files_to_clean('.', 'demo')).to eq([]) }.to output(/Refusing/).to_stderr
    end
  end

  describe '.reset_dir' do
    it 'wipes a generated dir and leaves only the ownership marker' do
      write_manifest('plug', {'metadata' => {'generator' => 'ruly'}})
      File.write('plug/stale.txt', "old\n")
      described_class.reset_dir('plug')
      expect(Dir.children('plug')).to eq(['.claude-plugin'])
      expect(described_class.generated?('plug')).to be(true)
    end
  end

  describe '.replace_dir' do
    before do
      write_manifest('plug', {'metadata' => {'generator' => 'ruly'}})
      File.write('plug/old.txt', "old\n")
    end

    it 'builds into an emptied dir and drops the previous plugin on success' do
      expect(described_class.replace_dir('plug') { Dir.children('plug') }).to eq(['.claude-plugin'])
      expect([File.exist?('plug/old.txt'), Dir.children('.')]).to eq([false, ['plug']])
    end

    it 'puts the previous plugin back when the build raises' do
      expect { described_class.replace_dir('plug') { raise Ruly::Error, 'boom' } }.to raise_error(Ruly::Error, 'boom')
      expect([File.read('plug/old.txt'), Dir.children('.')]).to eq(["old\n", ['plug']])
    end

    it 'removes a failed first build' do
      expect { described_class.replace_dir('fresh') { raise Ruly::Error, 'boom' } }.to raise_error(Ruly::Error)
      expect(File.exist?('fresh')).to be(false)
    end
  end

  describe '.rules_skill_description' do
    it 'names the recipe and its description' do
      expect(described_class.rules_skill_description('demo', {'description' => 'Team rules'}))
        .to eq("Rules from the ruly recipe 'demo' (Team rules). Invoke before starting any task in this project.")
    end

    it 'drops the parenthesis without a description' do
      expect(described_class.rules_skill_description('demo', {}))
        .to eq("Rules from the ruly recipe 'demo'. Invoke before starting any task in this project.")
    end

    it 'truncates to 1,536 characters' do
      expect(described_class.rules_skill_description('demo', {'description' => 'x' * 2000}).length).to eq(1536)
    end
  end

  describe '.notices' do
    let(:lines) { described_class.notices('demo', {}) }

    it 'says plugins cannot carry always-on instructions and names the rules skill' do
      expect(lines.first).to include('cannot carry always-on instructions', '/demo:demo-rules')
    end

    it 'points to ruly squash for always-on rules' do
      expect(lines.first).to include('`ruly squash demo` (CLAUDE.local.md)')
    end
  end

  describe 'ScriptManager.flat_skill_name' do
    {
      'notes.md' => 'notes',
      'rules/skills/deploy.md' => 'deploy',
      'rules/skills/git/commit.md' => 'git-commit',
      'rules/skills/tdd/SKILL.md' => 'tdd'
    }.each do |path, name|
      it "maps #{path} to #{name}" do
        expect(Ruly::Services::ScriptManager.flat_skill_name(path)).to eq(name)
      end
    end
  end

  describe 'ScriptManager.save_skill_files' do
    let(:files) { [{content: "# TDD\n", path: 'rules/skills/tdd/SKILL.md'}] }
    let(:deps) { {find_rule_file: ->(_p) {}, parse_frontmatter: ->(c) { [{}, c] }, strip_metadata: ->(c) { c }} }

    it 'writes DIR/<flat name>/SKILL.md with skills_dir:' do
      Ruly::Services::ScriptManager.save_skill_files(files, skills_dir: 'out/skills', **deps)
      expect([File.file?('out/skills/tdd/SKILL.md'), File.exist?('out/skills/tdd/SKILL')]).to eq([true, false])
    end

    it 'keeps the nested .claude/skills path without skills_dir:' do
      Ruly::Services::ScriptManager.save_skill_files(files, **deps)
      expect(File.file?('.claude/skills/tdd/SKILL/SKILL.md')).to be(true)
    end
  end

  describe 'ScriptManager.save_command_files' do
    let(:command) { {content: "# Ship\n", path: 'rules/commands/ship.md'} }

    it 'writes under commands_dir:' do
      Ruly::Services::ScriptManager.save_command_files([command], nil, commands_dir: 'out/commands')
      expect([File.file?('out/commands/ship.md'), File.exist?('.claude')]).to eq([true, false])
    end

    it 'writes under .claude/commands by default' do
      Ruly::Services::ScriptManager.save_command_files([command], nil)
      expect(File.file?('.claude/commands/ship.md')).to be(true)
    end
  end

  describe '.check_paths!' do
    def check(commands: [], skills: [])
      described_class.check_paths!('plug', command_files: commands.map { |p| {content: '', path: p} },
                                           recipe_config: {}, recipe_name: 'demo',
                                           skill_files: skills.map { |p| {content: '', path: p} })
    end

    it 'accepts the fixture skills and commands' do
      skills = %w[rules/skills/deploy.md rules/skills/tdd/SKILL.md]
      expect { check(commands: %w[rules/commands/ship.md], skills:) }.not_to raise_error
    end

    it 'refuses a skill that collides with the rules skill' do
      expect { check(skills: %w[rules/skills/demo-rules.md]) }
        .to raise_error(Ruly::Error, /collides with the generated rules skill demo-rules/)
    end

    it 'refuses a skill whose flattened name is unsafe' do
      expect { check(skills: %w[rules/skills/...md]) }.to raise_error(Ruly::Error, /unsafe plugin skill name/)
    end

    it 'refuses a command path that escapes DIR/commands' do
      expect { check(commands: %w[rules/commands/../../../evil.md]) }.to raise_error(Ruly::Error, /escapes/)
    end

    it 'warns when two skills flatten to the same name' do
      expect { check(skills: %w[rules/skills/a/b.md rules/skills/a-b.md]) }
        .to output(/both map to plugin skill 'a-b'/).to_stderr
    end

    ['rules/skills/.hidden.md', 'rules/skills/a..b.md'].each do |path|
      it "refuses the skill #{path}, which is not a safe plugin name" do
        expect { check(skills: [path]) }.to raise_error(Ruly::Error, /unsafe plugin skill name/)
      end
    end
  end

  describe '.check_skill_names! with claimed skills (subagent skills)' do
    let(:claimed) { described_class.skill_claims([{path: 'rules/skills/deploy.md'}]) }

    def check(*paths) = described_class.check_skill_names!(paths.map { |p| {path: p} }, 'demo', claimed)

    it 'refuses the rules skill name' do
      expect { check('rules/sub/skills/demo-rules.md') }.to raise_error(Ruly::Error, /collides with the generated/)
    end

    it 'warns when a claimed name comes from another file' do
      expect { check('rules/sub/skills/deploy.md') }.to output(/both map to plugin skill 'deploy'/).to_stderr
    end

    it 'is silent for the same file and records new names' do
      expect { expect(check('rules/skills/deploy.md', 'rules/skills/review.md').keys).to eq(%w[deploy review]) }
        .not_to output.to_stderr
    end
  end

  describe '.hook_command' do
    let(:root) { '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"' }

    before do
      FileUtils.mkdir_p('plug/scripts')
      File.write('plug/scripts/notify.sh', "#!/bin/sh\n")
    end

    it 'rewrites a copied script to the quoted plugin-root path' do
      expect(described_class.hook_command('.claude/scripts/notify.sh', 'plug')).to eq(root)
    end

    it 'quotes an already double-quoted reference once' do
      expect(described_class.hook_command('"./x" ".claude/scripts/notify.sh"', 'plug')).to eq("\"./x\" #{root}")
    end

    it 'keeps the prefix and suffix' do
      expect(described_class.hook_command('bash .claude/scripts/notify.sh --flag', 'plug')).to eq("bash #{root} --flag")
    end

    {
      '"$HOME/.claude/scripts/x.sh" --y' => '$HOME/.claude/scripts/x.sh',
      '~/.claude/scripts/x.sh' => '~/.claude/scripts/x.sh'
    }.each do |command, token|
      it "keeps #{command} and names it on stderr" do
        result = nil
        expect { result = described_class.hook_command(command, 'plug') }
          .to output(/references #{Regexp.escape(token)}, which is outside the plugin; left unchanged/).to_stderr
        expect(result).to eq(command)
      end
    end

    {
      '"$CLAUDE_PROJECT_DIR"/.claude/scripts/notify.sh' => '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"',
      '"$CLAUDE_PROJECT_DIR/.claude/scripts/notify.sh" a' => '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh" a',
      '"${CLAUDE_PROJECT_DIR}"/.claude/scripts/notify.sh --x' => '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh" --x',
      '$CLAUDE_PROJECT_DIR/.claude/scripts/notify.sh' => '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"',
      './.claude/scripts/notify.sh && ./.claude/scripts/notify.sh' =>
        '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh" && "${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"',
      'bash -c ".claude/scripts/notify.sh --x"' => 'bash -c "${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh --x"',
      'bash -c "echo \\"a\\"; .claude/scripts/notify.sh"' =>
        'bash -c "echo \\"a\\"; ${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"',
      "sh -c '.claude/scripts/notify.sh'" => "sh -c '${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh'"
    }.each do |command, rewritten|
      it "rewrites #{command} without breaking its quoting" do
        expect { expect(described_class.hook_command(command, 'plug')).to eq(rewritten) }.not_to output.to_stderr
      end
    end

    it 'keeps and warns about a script that is not a recipe script' do
      result = nil
      expect { result = described_class.hook_command('.claude/scripts/other.sh', 'plug') }
        .to output(%r{\.claude/scripts/other\.sh, which is not a recipe script; left unchanged}).to_stderr
      expect(result).to eq('.claude/scripts/other.sh')
    end
  end

  describe '.write_hooks' do
    let(:hooks) { {'Stop' => [{'hooks' => [{'command' => '.claude/scripts/notify.sh', 'type' => 'command'}]}]} }

    before do
      FileUtils.mkdir_p('plug/scripts')
      File.write('plug/scripts/notify.sh', "#!/bin/sh\n")
    end

    it 'writes the hooks under a top-level hooks key with rewritten commands' do
      described_class.write_hooks('plug', {'hooks' => hooks})
      expect(JSON.parse(File.read('plug/hooks/hooks.json')))
        .to eq('hooks' => {'Stop' => [{'hooks' => [{'command' => '"${CLAUDE_PLUGIN_ROOT}/scripts/notify.sh"',
                                                    'type' => 'command'}]}]})
    end

    it 'leaves the recipe hooks unchanged' do
      described_class.write_hooks('plug', {'hooks' => hooks})
      expect(hooks.dig('Stop', 0, 'hooks', 0, 'command')).to eq('.claude/scripts/notify.sh')
    end

    it 'writes nothing for empty or missing hooks' do
      described_class.write_hooks('plug', {'hooks' => {}})
      described_class.write_hooks('plug', {})
      expect(File.exist?('plug/hooks')).to be(false)
    end
  end

  describe '.literal_secret_servers' do
    it 'names servers with a literal env value only' do
      servers = {'a' => {'env' => {'K' => 'v'}}, 'b' => {'env' => {'K' => '${K}'}}, 'c' => {'command' => 'x'}}
      expect(described_class.literal_secret_servers(servers)).to eq(['a'])
    end

    it 'names servers with a literal headers value' do
      servers = {'e' => {'env' => {'K' => ''}}, 'h' => {'headers' => {'Authorization' => 'Bearer abc'}}}
      expect(described_class.literal_secret_servers(servers)).to eq(['h'])
    end
  end

  describe '.write_mcp' do
    def stub_servers(servers)
      allow(Ruly::Services::MCPManager).to receive(:load_mcp_servers_from_config).and_return(servers)
    end

    it 'writes the servers to DIR/.mcp.json' do
      stub_servers('grafana' => {'command' => 'mcp-grafana', 'env' => {'URL' => '${URL}'}})
      described_class.write_mcp('plug', ['grafana'])
